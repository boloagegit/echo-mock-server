package com.echo.dto;

import com.echo.entity.Protocol;
import com.fasterxml.jackson.annotation.JsonAnySetter;
import com.fasterxml.jackson.annotation.JsonIgnore;
import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.databind.JsonNode;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Declarative rules file.
 *
 * <p>apiVersion, kind and metadata identification fields are managed by the system. ID is generated by the backend when creating a rule;
 * When updating, bind the rule ID with the request path, and perform an optimistic lock check based on resourceVersion.
 * spec represents the complete desired state, not the partial patch.</p>
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@JsonInclude(JsonInclude.Include.NON_NULL)
public class RuleApplyDocument {

    public static final String API_VERSION = "echo.mock/v1";
    /** v2: All fields of v1, and also supports {@code spec.match} (structured conditions). */
    public static final String API_VERSION_V2 = "echo.mock/v2";
    public static final String KIND = "Rule";

    private String apiVersion;
    private String kind;
    private Metadata metadata;
    private Spec spec;

    @JsonIgnore
    @Builder.Default
    private Map<String, JsonNode> unknownFields = new LinkedHashMap<>();

    @JsonAnySetter
    public void captureUnknownField(String name, JsonNode value) {
        unknownFields.put(name, value);
    }

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    @JsonInclude(JsonInclude.Include.NON_NULL)
    public static class Metadata {
        private String id;
        private Long resourceVersion;

        @JsonIgnore
        @Builder.Default
        private Map<String, JsonNode> unknownFields = new LinkedHashMap<>();

        @JsonAnySetter
        public void captureUnknownField(String name, JsonNode value) {
            unknownFields.put(name, value);
        }
    }

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    @JsonInclude(JsonInclude.Include.NON_NULL)
    public static class Spec {
        private Protocol protocol;
        private String targetHost;
        private String matchKey;
        private String method;
        private String bodyCondition;
        private String queryCondition;
        private String headerCondition;
        /** Structured condition ({@code echo.mock/v2} only); mutually exclusive with the three legacy condition fields. */
        private JsonNode match;
        private Integer priority;
        private String description;
        private Boolean enabled;

        @JsonProperty("protected")
        private Boolean protectedRule;

        private Map<String, String> tags;
        private Long responseId;
        private JsonNode responseBody;
        private String responseDescription;
        private Integer status;
        private Map<String, String> responseHeaders;
        private Long delayMs;
        private Long maxDelayMs;
        private Boolean sseEnabled;
        private Boolean sseLoopEnabled;
        private String responseContentType;
        private String action;
        private String forwardTargetMode;
        private Long httpTargetConnectionId;
        private String jmsTargetConnectionId;
        private String faultType;
        private String scenarioName;
        private String requiredScenarioState;
        private String newScenarioState;

        @JsonIgnore
        @Builder.Default
        private Map<String, JsonNode> unknownFields = new LinkedHashMap<>();

        @JsonAnySetter
        public void captureUnknownField(String name, JsonNode value) {
            unknownFields.put(name, value);
        }
    }
}
